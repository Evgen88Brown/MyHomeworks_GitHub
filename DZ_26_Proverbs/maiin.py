def create_all_combinations(proverbs: Set[str], variants: Set[str])-> Set[str]:
    """
    Генерирует все возможные комбинации пословиц с заменой слова "Ум" на каждый из вариантов.

    Принимает:
        proverbs (set[str]): множество исходных пословиц, содержащих "Ум".
        variants (set[str]): множество слов для замены.

    Возвращает:
        set[str]: множество уникальных строк после замены.
    """
    combinations: Set[str] = set()
    for proverb in proverbs:
        for variant in variants:
        # Заменяем "Ум" на вариант. Учитываем, что в пословицах "Ум" с большой буквы.
            new_proverb = proverb.replace("Ум", variant)
            combinations.add(new_proverb)
    return combinations

def pick_items(source: Set[str], count: int)-> Set[str]:
    """
    Извлекает указанное количество элементов из множества-источника без возврата.

    Использует метод pop() для безвозвратного удаления элементов из source.
    Гарантирует уникальность выбранных элементов.

    Принимает:
        source (set[str]): исходное множество, из которого будут извлечены элементы.
        count (int): количество элементов для извлечения.

    Возвращает:
        set[str]: множество с извлеченными элементами.
    """
    results: Set[str] = set()
    while len(results) < count:
        # pop() удаляет и возвращает произвольный элемент множества
        item = source.pop()
        results.add(item)
    return results

def print_results(results: Set[str])-> None:
    """
    Выводит на экран пронумерованный список пословиц.

    Принимает:
        results (set[str]): множество пословиц для отображения.

    Вывод форматируется с ручной нумерацией.
    """
    print("\nСгенерированные пословицы: ")
    counter = 0
    for proverb in results:
        counter += 1
        print(f"{counter}, {proverb}")

